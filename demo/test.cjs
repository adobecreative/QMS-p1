const { chromium } = require('/home/claude/.npm-global/lib/node_modules/playwright');
const fs = require('fs');
const V = '/home/claude/facilities-tracker/public/vendor/';
let failed = 0;
const ok = (c, label, extra) => { console.log((c ? 'PASS ' : 'FAIL ') + label + (extra !== undefined ? '  -> ' + extra : '')); if (!c) failed++; };
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  page.on('console', (m) => { if (m.type() === 'error' && !/net::ERR|Failed to load resource/.test(m.text())) errors.push('console: ' + m.text().slice(0, 300)); });
  await page.route('https://cdnjs.cloudflare.com/**', (r) => { const f = V + r.request().url().split('/').pop(); r.fulfill({ status: 200, contentType: 'application/javascript', body: fs.readFileSync(f) }); });
  await page.route('https://fonts.googleapis.com/**', (r) => r.abort());
  await page.goto('file:///mnt/user-data/outputs/facilities-demo.html');
  await page.waitForSelector('.cards');
  ok((await page.locator('.card-num').allInnerTexts()).join(',') === '3,2,2,1', 'dashboard cards 3,2,2,1', (await page.locator('.card-num').allInnerTexts()).join(','));
  ok((await page.locator('.files-table tbody tr').count()) === 9, '9 sample files');
  ok((await page.locator('.nav-link').count()) === 6, 'super admin nav');
  ok((await page.locator('a[href]').count()) === 0, 'no real links on the dashboard (nothing for a viewer to intercept)');
  await page.locator('.files-table tbody tr').nth(0).locator('a.btn').click();
  await page.waitForSelector('.doc-layout');
  ok((await page.locator('a[href]').count()) === 0 && (await page.evaluate(() => location.hash)) !== undefined, 'View PDF navigates inside the page, no links in the reader');
  await page.locator('.nav-link').nth(0).click();
  await page.waitForSelector('.cards');
  const dlg = () => page.locator('dialog[open]');
  await page.screenshot({ path: '/tmp/demo-dash-phone.png' });
  // reader
  await page.locator('.nav-link').nth(1).click();
  await page.waitForSelector('.pdf-canvas', { timeout: 20000 });
  await page.waitForFunction(() => /3/.test(document.querySelector('.pdf-page').textContent), null, { timeout: 20000 });
  await page.waitForTimeout(600);
  const ink = await page.evaluate(() => { const c = document.querySelector('.pdf-canvas'); const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 0; i < d.length; i += 4) if (d[i] < 100) n++; return n; });
  ok(ink > 1000, 'PDF drawn in the reader', (await page.locator('.pdf-page').innerText()) + ' ink=' + ink);
  await page.locator('.pdf-bar .btn-icon').nth(1).click();
  await page.waitForFunction(() => /2/.test(document.querySelector('.pdf-page').textContent.replace('3', '')));
  ok(true, 'next page');
  await page.screenshot({ path: '/tmp/demo-reader-phone.png', fullPage: true });
  // roles
  await page.locator('#demo-user').selectOption('3');
  await page.waitForFunction(() => document.querySelectorAll('.nav-link').length === 2);
  await page.waitForSelector('.doc-layout');
  ok(true, 'viewer: 2 nav items, lands on reader');
  await page.locator('#demo-user').selectOption('2');
  await page.waitForSelector('.cards');
  await page.waitForFunction(() => document.querySelectorAll('.files-table tbody tr').length === 4);
  ok(true, 'dept admin: only 4 Safety files');
  // dept admin adds a file with a real upload
  await page.locator('.page-head .btn-primary').click();
  await dlg().locator('input[type=text]').nth(0).fill('إجراء فحص الطفايات');
  await dlg().locator('input[type=text]').nth(1).fill('FM-SAF-030');
  await dlg().locator('input[type=date]').nth(1).fill('2030-01-01');
  await dlg().locator('input[type=file]').setInputFiles('/home/claude/demo/sample.pdf');
  await dlg().locator('button[type=submit]').click();
  await page.waitForSelector('td:has-text("FM-SAF-030")');
  ok(true, 'add file works in demo');
  await page.locator('.files-table tbody tr', { hasText: 'FM-SAF-030' }).locator('a.btn').click();
  await page.waitForFunction(() => document.querySelector('.pdf-page') && /3/.test(document.querySelector('.pdf-page').textContent), null, { timeout: 20000 });
  ok(true, 'uploaded file opens');
  // super admin: logs, settings, export
  await page.locator('#demo-user').selectOption('1');
  await page.waitForFunction(() => document.querySelectorAll('.nav-link').length === 6);
  await page.locator('.nav-link').nth(4).click();
  await page.waitForSelector('tbody tr');
  ok((await page.locator('tbody tr').count()) === 7, 'logs: 6 seeded + 1 new', await page.locator('tbody tr').count());
  await page.locator('.nav-link').nth(5).click();
  await page.waitForSelector('form.settings');
  await page.locator('.settings .actions .btn').nth(1).click();
  await page.waitForSelector('.toast-bad');
  ok(/Gmail/.test(await page.locator('.toast-bad').innerText()), 'test email explains demo limit');
  await page.locator('.top .lang-btn').nth(1).click();
  await page.waitForFunction(() => document.documentElement.dir === 'ltr');
  ok((await page.locator('#demo-title').innerText()) === 'Demo for review.', 'demo bar follows language');
  await page.locator('.top .lang-btn').nth(0).click();
  await page.locator('.nav-link').nth(0).click();
  await page.waitForSelector('.cards');
  const over = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  ok(over <= 0, 'no sideways scroll on phone', over);
  // sign out and back in with the form
  await page.locator('.user-btn').click();
  await dlg().locator('.btn-end').click();
  await page.waitForSelector('.auth-card form');
  await page.locator('.auth-card input').nth(0).fill('viewer@demo.example');
  await page.locator('.auth-card input').nth(1).fill('demo1234');
  await page.locator('.auth-card button[type=submit]').click();
  await page.waitForSelector('.doc-layout');
  ok((await page.locator('#demo-user').inputValue()) === '3', 'login form works, bar in sync');
  ok(errors.length === 0, 'no JavaScript errors', errors.join(' | '));
  await browser.close();
  console.log(failed ? failed + ' FAILED' : 'ALL PASSED');
})().catch((e) => { console.log('CRASH ' + e.message.split('\n').slice(0, 5).join(' / ')); process.exit(2); });
